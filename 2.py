# EJERCICIO 2: title() y replace()
# 1. Cadena original, 2. Formato Título, 3. Reemplazo
texto = "patrick cardoza"
print(texto)

## Convertir la primera letra de cada palabra en mayúscula
texto_titulo = texto.title()
print(texto_titulo)

## Reemplazar "Su Nombre" por "Su Apellido"
texto_reemplazado = texto_titulo.replace("Patrick", "Cardoza")
print(texto_reemplazado)
